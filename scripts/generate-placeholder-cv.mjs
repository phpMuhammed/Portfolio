import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const cvDir = path.resolve(__dirname, '..', 'public', 'cv');
mkdirSync(cvDir, { recursive: true });
const outPath = path.join(cvDir, 'Mohammed_Ayman_Musabeh_Senior_Full_Stack_Developer_CV.pdf');

function textLine(text, x, y, size) {
  const escaped = text.replace(/([()\\])/g, '\\$1');
  return `BT /F1 ${size} Tf ${x} ${y} Td (${escaped}) Tj ET\n`;
}

const lines = [
  textLine('Placeholder CV', 50, 720, 20),
  textLine('This file is a placeholder generated by the build tooling.', 50, 680, 12),
  textLine('Replace it with the real CV before deploying:', 50, 662, 12),
  textLine('public/cv/Mohammed_Ayman_Musabeh_Senior_Full_Stack_Developer_CV.pdf', 50, 644, 12),
].join('');

const streamContent = lines;
const streamLength = Buffer.byteLength(streamContent, 'utf-8');

const objects = [
  '<< /Type /Catalog /Pages 2 0 R >>',
  '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
  '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>',
  `<< /Length ${streamLength} >>\nstream\n${streamContent}endstream`,
  '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
];

let pdf = '%PDF-1.4\n';
const offsets = [0];

objects.forEach((body, index) => {
  offsets.push(Buffer.byteLength(pdf, 'utf-8'));
  pdf += `${index + 1} 0 obj\n${body}\nendobj\n`;
});

const xrefOffset = Buffer.byteLength(pdf, 'utf-8');
pdf += `xref\n0 ${objects.length + 1}\n`;
pdf += '0000000000 65535 f \n';
for (let i = 1; i <= objects.length; i++) {
  pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
}
pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;

writeFileSync(outPath, pdf, 'utf-8');
console.log(`Generated placeholder CV at ${outPath}`);
